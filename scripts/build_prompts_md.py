"""CLI: build prompts.md from the files in prompts/ (never edited by hand).

  python -m scripts.build_prompts_md          # write prompts.md
  python -m scripts.build_prompts_md --check  # fail if prompts.md is stale or a prompt differs

Every prompt version is copied byte-for-byte inside a fence, with its SHA-256, so a reader can
verify it against the file and the generation metadata in generated/raw/.
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROMPTS_DIR = ROOT / "prompts"
RAW_DIR = ROOT / "generated" / "raw"
OUTPUT = ROOT / "prompts.md"
MODULES = {"login": "Login", "dashboard": "Dashboard", "api": "REST API"}
VERSION_FILE = re.compile(r"^(?P<module>[a-z]+)\.v(?P<n>\d+)\.md$")


def prompt_versions(module: str) -> list[Path]:
    files = [p for p in PROMPTS_DIR.glob(f"{module}.v*.md") if VERSION_FILE.match(p.name)]
    return sorted(files, key=lambda p: int(VERSION_FILE.match(p.name)["n"]))


def fence_for(text: str) -> str:
    longest = max((len(m) for m in re.findall(r"`+", text)), default=0)
    return "`" * max(4, longest + 1)


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def runs_for(module: str, version: str) -> list[dict]:
    runs = []
    for raw in sorted(RAW_DIR.glob(f"{module}.{version}.*Z.json")):
        meta = json.loads(raw.read_text(encoding="utf-8"))["metadata"]
        report_file = raw.with_name(raw.name.removesuffix(".json") + ".report.json")
        report = json.loads(report_file.read_text(encoding="utf-8"))
        runs.append({
            "stem": raw.name.removesuffix(".json"),
            "passed": report["passed"],
            "cases": report["case_count"],
            "finish_reason": meta.get("finish_reason")
            or json.loads(raw.read_text(encoding="utf-8"))["api_response"]["choices"][0].get(
                "finish_reason"),
            "max_tokens": meta.get("max_completion_tokens", "provider default"),
        })
    return runs


def module_notes() -> tuple[dict[str, str], bool]:
    path = PROMPTS_DIR / "notes.md"
    if not path.exists():
        return {}, False
    text = path.read_text(encoding="utf-8")
    draft = "status: DRAFT" in text
    sections = re.split(r"^## ", text, flags=re.MULTILINE)[1:]
    notes = {}
    for section in sections:
        name, _, body = section.partition("\n")
        notes[name.strip()] = body.strip()
    return notes, draft


def accepted() -> dict:
    path = ROOT / "generated" / "accepted.json"
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def build() -> str:
    notes, notes_draft = module_notes()
    accepted_runs = accepted()
    out: list[str] = [
        "# Prompts",
        "",
        "> Generated by `scripts/build_prompts_md.py` from the files in `prompts/`. Do not edit"
        " by hand.",
        "> Every prompt is copied byte-for-byte from its file; the SHA-256 matches the file and"
        " the run metadata in `generated/raw/`.",
        "",
        "## Contents",
        "",
        "- [How to re-run these prompts](#how-to-re-run-these-prompts)",
        "- [Settings used for every run](#settings-used-for-every-run)",
    ]
    out += [f"- [{title}](#{title.lower().replace(' ', '-')})" for title in MODULES.values()]
    out += [
        "- [Task 3: Flaky Test Classifier prompts](#task-3-flaky-test-classifier-prompts)",
        "",
        "## How to re-run these prompts",
        "",
        "1. Get a free API key at https://console.groq.com/keys.",
        "2. `cp .env.example .env` and set `LLM_API_KEY`.",
        "3. `pip install -r requirements.txt`",
        "4. Run one module and version, e.g. "
        "`python -m scripts.generate_tests --module login --version v4`.",
        "",
        "The script sends the prompt file unchanged and saves the verbatim response plus a"
        " validation report under `generated/raw/`. Compare your report with the one listed"
        " below. Groq does not return byte-identical output even at temperature 0, so expect"
        " the same structure and coverage, not the same wording.",
        "",
        "On the free tier, run modules one at a time: each run uses about 8-10k tokens and the"
        " limit is 8,000 tokens per minute. The client backs off and retries automatically.",
        "",
        "To use a local model instead, set `LLM_BASE_URL=http://localhost:11434/v1` and"
        " `LLM_MODEL` to an Ollama model; nothing else changes.",
        "",
        "## Settings used for every run",
        "",
        "| Setting | Value |",
        "|---|---|",
        "| Provider | Groq, OpenAI-compatible `POST /chat/completions` |",
        "| Model | `openai/gpt-oss-120b` |",
        "| Messages | the whole prompt file as one `user` message; no system message |",
        "| `temperature` | `0` |",
        "| `response_format` | `{\"type\": \"json_object\"}` |",
        "| `max_completion_tokens` | `16384` (the very first Login v1 run used the provider"
        " default and was truncated; see below) |",
        "",
    ]

    for module, title in MODULES.items():
        versions = prompt_versions(module)
        out += [f"## {title}", ""]
        if not versions:
            out += ["_No prompts yet._", ""]
            continue

        out += ["### What didn't work the first time, and what changed", ""]
        if notes_draft:
            out += ["> Draft, awaiting Kartikey's confirmation.", ""]
        out += [notes.get(module, "_No note yet._"), ""]

        acc = accepted_runs.get(module, {})
        out += [
            "### Runs",
            "",
            "| Prompt | Run | Validation | Cases | finish_reason | max_completion_tokens |",
            "|---|---|---|---|---|---|",
        ]
        for path in versions:
            version = path.name.split(".")[1]
            for run in runs_for(module, version):
                mark = " **(accepted)**" if acc.get("raw_response", "").endswith(
                    run["stem"] + ".json") else ""
                result = "PASS" if run["passed"] else "FAIL"
                out.append(
                    f"| {version} | [`{run['stem']}`](generated/raw/{run['stem']}.report.md){mark}"
                    f" | {result} | {run['cases']} | {run['finish_reason']}"
                    f" | {run['max_tokens']} |"
                )
        out.append("")

        for path in versions:
            version = path.name.split(".")[1]
            text = path.read_text(encoding="utf-8")
            fence = fence_for(text)
            out += [
                f"### {title} prompt {version}",
                "",
                f"File: `prompts/{path.name}` · SHA-256 `{sha256(path)}`",
                "",
            ]
            if version != "v1":
                out += [f"Why this version exists: see `prompts/revisions.md`, section"
                        f" \"{version}\".", ""]
            out += [f"{fence}markdown", text.rstrip("\n"), fence, ""]

    out += ["## Task 3: Flaky Test Classifier prompts", ""]
    classifier = sorted(PROMPTS_DIR.glob("classifier.v*.md"),
                        key=lambda p: int(VERSION_FILE.match(p.name)["n"]))
    if not classifier:
        out += ["_Added in Phase 5._", ""]
    for path in classifier:
        text = path.read_text(encoding="utf-8")
        fence = fence_for(text)
        out += [f"### Classifier prompt {path.name.split('.')[1]}", "",
                f"File: `prompts/{path.name}` · SHA-256 `{sha256(path)}`", "",
                f"{fence}markdown", text.rstrip("\n"), fence, ""]
    return "\n".join(out)


def check_blocks(markdown: str) -> list[str]:
    """Every fenced prompt in prompts.md must equal its file (ignoring the final newline)."""
    problems = []
    pattern = re.compile(
        r"File: `prompts/(?P<name>[^`]+)` · SHA-256 `[0-9a-f]+`\n\n(?:Why[^\n]*\n\n)?"
        r"(?P<fence>`{4,})markdown\n(?P<body>.*?)\n(?P=fence)\n", re.DOTALL)
    found = 0
    for match in pattern.finditer(markdown):
        found += 1
        expected = (PROMPTS_DIR / match["name"]).read_text(encoding="utf-8").rstrip("\n")
        if match["body"] != expected:
            problems.append(f"{match['name']}: block differs from the file")
    expected_count = len(list(PROMPTS_DIR.glob("*.v*.md")))
    if found != expected_count:
        problems.append(f"found {found} prompt blocks, expected {expected_count}")
    return problems


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    content = build() + "\n"
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        problems = check_blocks(current)
        if current != content:
            problems.append("prompts.md is stale; run python -m scripts.build_prompts_md")
        for problem in problems:
            print(f"error: {problem}")
        return 1 if problems else 0

    OUTPUT.write_text(content, encoding="utf-8", newline="\n")
    problems = check_blocks(content)
    for problem in problems:
        print(f"error: {problem}")
    print(f"Wrote {OUTPUT.name}: {len(content.splitlines())} lines")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
