"""CLI: build docs/traceability.md (generated case -> test -> status) from a test run.

  python -m pytest                          # writes reports/run-<id>/case-results.json
  python -m scripts.build_traceability      # uses the latest run
  python -m scripts.build_traceability --run 20261023-011500
"""

import argparse
import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / "reports"
OUTPUT = ROOT / "docs" / "traceability.md"
MODULES = {"login": "Login", "dashboard": "Dashboard", "api": "REST API"}

# Generated cases deliberately not automated, with the reason. Every other unautomated case
# is listed as "not selected" (only P0 cases plus a few per area were automated).
NOT_AUTOMATED = {
    "DASH-008": "Generated expectation is wrong: expects the error code 'validation_error' in "
                "widget-error; the UI shows the error message (see the v3 review note).",
    "DASH-010": "Generated expectation is wrong: its steps use a tampered cookie, which the app "
                "treats as no session (redirect to /login without ?reason=expired). Checked by "
                "running the case as generated.",
}


def latest_run_id() -> str:
    return (REPORTS / "latest-run.txt").read_text(encoding="utf-8").strip()


def load_results(run_id: str) -> dict[str, list[dict]]:
    path = REPORTS / f"run-{run_id}" / "case-results.json"
    if not path.exists():
        raise SystemExit(f"No case results in {path.relative_to(ROOT)}; run the tests first.")
    by_case: dict[str, list[dict]] = {}
    for nodeid, entry in json.loads(path.read_text(encoding="utf-8")).items():
        for case_id in entry["cases"]:
            by_case.setdefault(case_id, []).append({"nodeid": nodeid, **entry})
    return by_case


def build(run_id: str) -> str:
    results = load_results(run_id)
    accepted = json.loads((ROOT / "generated" / "accepted.json").read_text(encoding="utf-8"))
    lines = [
        "# Traceability: generated cases → automated tests",
        "",
        "> Generated by `scripts/build_traceability.py` from `generated/*.json` and the test run"
        f" `reports/run-{run_id}/case-results.json`. Do not edit by hand.",
        "",
        "| Module | Generated cases | P0 | Automated | Passed in this run |",
        "|---|---|---|---|---|",
    ]
    sections: list[str] = []
    for module, title in MODULES.items():
        cases = json.loads((ROOT / "generated" / f"{module}.json").read_text(encoding="utf-8"))[
            "cases"]
        automated = [c for c in cases if c["id"] in results]
        passed = [c for c in automated
                  if all(r["outcome"] == "passed" for r in results[c["id"]])]
        p0 = sum(1 for c in cases if c["priority"] == "P0")
        lines.append(f"| {title} | {len(cases)} | {p0} | {len(automated)} | {len(passed)} |")

        version = accepted.get(module, {}).get("prompt_version", "?")
        sections += [
            "",
            f"## {title} (accepted prompt {version})",
            "",
            "| Case | Priority | Coverage area | Title | Test | Status |",
            "|---|---|---|---|---|---|",
        ]
        for case in cases:
            runs = results.get(case["id"], [])
            if runs:
                test = "<br>".join(f"`{r['nodeid']}`" for r in runs)
                status = ", ".join(sorted({r["outcome"] for r in runs}))
            elif case["id"] in NOT_AUTOMATED:
                test, status = "—", f"not automated: {NOT_AUTOMATED[case['id']]}"
            elif not case.get("automation_candidate"):
                test, status = "—", "not an automation candidate"
            else:
                test, status = "—", "not selected"
            title_text = case["title"].replace("|", "\\|")
            sections.append(f"| {case['id']} | {case['priority']} | {case['coverage_area']} |"
                            f" {title_text} | {test} | {status} |")

    unmatched = sorted(set(results) - {c for m in MODULES for c in _ids(m)})
    if unmatched:
        sections += ["", f"Tests linked to unknown case IDs: {', '.join(unmatched)}"]
    outcomes = Counter(r["outcome"] for runs in results.values() for r in runs)
    lines += ["", f"Test outcomes in this run: {dict(sorted(outcomes.items()))}."]
    return "\n".join(lines + sections) + "\n"


def _ids(module: str) -> list[str]:
    data = json.loads((ROOT / "generated" / f"{module}.json").read_text(encoding="utf-8"))
    return [c["id"] for c in data["cases"]]


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--run", help="run id (default: the latest run)")
    args = parser.parse_args()
    run_id = args.run or latest_run_id()
    OUTPUT.write_text(build(run_id), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} from run {run_id}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
